import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { Window } from 'happy-dom';
import { createServer } from 'vite';
import React, { act } from 'react';
import { collectManualWord, libraryJSON, parseLibrary, reviewQueue, STORAGE_KEY } from '../src/study.mjs';
import { lookupStudyWord } from '../src/study-dictionary.mjs';

const window = new Window({ url: 'https://komorebi-test.example/' });
for (const key of ['window', 'document', 'HTMLElement', 'HTMLDialogElement', 'MouseEvent', 'Event']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? window : window[key] });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () { this.open = false; };
const spoken = [];
Object.defineProperty(window, 'speechSynthesis', { value: { getVoices: () => [{ name: 'Japanese', lang: 'ja-JP' }], addEventListener() {}, removeEventListener() {}, cancel() {}, speak: utterance => spoken.push(utterance.text) } });
Object.defineProperty(window, 'SpeechSynthesisUtterance', { value: class { constructor(text) { this.text = text; } } });
const originalFetch = globalThis.fetch;
globalThis.fetch = async url => ({ ok: true, json: async () => JSON.parse(await readFile(`public${url}`, 'utf8')) });
const now = new Date();
let cards = collectManualWord([], { word: '図書館', reading: 'としょかん', definitions: [{ id: 'custom', source: 'custom', headword: '図書館', reading: 'としょかん', senses: [{ meanings: ['library'] }] }], examples: [{ source: 'custom', text: '図書館で勉強します。', english: 'I study at the library.' }] }, now);
cards[0].examples = [{ videoId: 'abcdefghijk', title: '練習', start: 1, end: 3, text: '図書館です。', english: 'It is a library.' }];
cards = collectManualWord(cards, { word: '猫', reading: 'ねこ' }, now);
cards = collectManualWord(cards, { word: '犬', reading: 'いぬ' }, now);
window.localStorage.setItem(STORAGE_KEY, libraryJSON(cards));
const server = await createServer({ server: { middlewareMode: true, ws: false }, appType: 'custom',
  define: { 'import.meta.env.VITE_SUPABASE_URL': '""', 'import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY': '""', 'import.meta.env.VITE_SUPABASE_ANON_KEY': '""' } });
const { createRoot } = await import('react-dom/client');
const mount = document.createElement('div'); document.body.append(mount);
const root = createRoot(mount);
const click = async element => { assert.ok(element); await act(async () => element.dispatchEvent(new window.MouseEvent('click', { bubbles: true }))); };
const nav = label => { document.querySelector('.mobile-menu').open = true; return [...document.querySelectorAll('.mobile-nav button')].find(button => button.textContent.endsWith(label)); };
try {
  const activeVideo = JSON.parse(await readFile('src/data/active-video.json', 'utf8'));
  const { default: MobileApp } = await server.ssrLoadModule(activeVideo.id ? '/src/MobileApp.jsx' : '/src/App.jsx');
  await act(async () => root.render(React.createElement(MobileApp)));
  assert.equal(document.querySelector('iframe'), null);
  assert.equal(document.querySelector('audio'), null);
  assert.equal(document.querySelector('.word-library').hidden, true);
  assert.ok(document.querySelector('.mobile-header'), 'Header is visible before starting');
  assert.equal(document.querySelector('.review-picker').hidden, false);
  async function countInput(label, value) {
    await act(async () => {
      const input = document.querySelector(`[aria-label="${label}"]`);
      Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(input, value);
      input.dispatchEvent(new window.Event('input', { bubbles: true }));
    });
  }
  await countInput('加入複習的單字數量', '2');
  await act(async () => document.querySelector('.review-picker').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
  assert.equal(document.querySelector('.review-picker').hidden, true, 'Starting practice hides the count form');
  assert.equal(document.querySelector('.mobile-header'), null, 'Practice removes the header');
  assert.ok(document.querySelector('.mobile-app.is-studying'));
  assert.equal(document.querySelector('.mobile-practice-remaining strong').textContent, '2');
  assert.equal(document.querySelector('.flashcard h2').textContent, cards[0].word);
  assert.equal(document.querySelector('.flashcard-answer'), null, 'Answer stays hidden on the front');
  await click(document.querySelector('.flip-button'));
  assert.ok(document.querySelector('.flashcard-answer').textContent.includes('I study at the library.'));
  assert.ok(document.querySelector('.flashcard-answer').textContent.includes('It is a library.'));
  assert.equal(document.querySelector('.flashcard-answer').tabIndex, 0, 'Scrollable answers can receive keyboard focus');
  await click(document.querySelector('[aria-label="添加複習單字"]'));
  assert.ok(document.querySelector('.mobile-practice-dialog').open);
  assert.equal(document.querySelector('.practice-dialog-count strong').textContent, '2');
  await click(document.querySelector('[aria-label="關閉添加單字視窗"]'));
  assert.equal(document.querySelector('.mobile-practice-dialog').open, false);
  assert.ok(document.querySelector('.flashcard.is-back'), 'Closing the picker retains the card face');
  await click(document.querySelector('[aria-label="添加複習單字"]'));
  await countInput('添加複習的單字數量', '1');
  await act(async () => document.querySelector('.mobile-practice-dialog form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
  assert.equal(document.querySelector('.mobile-practice-dialog').open, false);
  assert.equal(document.querySelector('.mobile-practice-remaining strong').textContent, '3', 'Adding words extends the existing queue');
  assert.ok(document.querySelector('.flashcard.is-back'), 'Adding words retains the current card face');
  assert.equal(document.querySelector('.example-source'), null, 'Mobile examples offer no video replay');
  await click(document.querySelector('[aria-label="朗讀例句"]'));
  assert.equal(spoken.at(-1), '図書館です。');
  const nextWord = reviewQueue(parseLibrary(window.localStorage.getItem(STORAGE_KEY)), new Date())[1].word;
  await click(document.querySelector('.rating-again'));
  assert.equal(parseLibrary(window.localStorage.getItem(STORAGE_KEY))[0].reviews.at(-1).rating, 1);
  assert.ok(parseLibrary(window.localStorage.getItem(STORAGE_KEY))[0].reviews.at(-1).id);
  assert.equal(document.querySelector('.flashcard h2').textContent, nextWord);
  assert.equal(document.querySelector('.mobile-practice-remaining strong').textContent, '3', 'Unfamiliar words still count as remaining');
  await click(document.querySelector('.flip-button'));
  await click(document.querySelector('.rating-good'));
  assert.equal(document.querySelector('.mobile-practice-remaining strong').textContent, '2', 'Familiar words leave the remaining count');
  await click(nav('收藏'));
  assert.equal(document.querySelector('.mobile-menu').open, false, 'Choosing a destination closes the menu');
  assert.ok(document.querySelector('.mobile-header'));
  assert.equal(document.querySelector('.review-session').hidden, true);
  assert.equal(document.querySelector('.word-library').hidden, false);
  await click([...document.querySelectorAll('.saved-word-open')].find(button => button.textContent.startsWith('図書館')));
  assert.equal(document.querySelector('dialog[open] h2').textContent, '図書館');
  assert.ok(document.querySelector('dialog[open]').textContent.includes('I study at the library.'));
  assert.equal(document.querySelector('dialog .word-context button'), null);
  await click(document.querySelector('.word-close'));
  await click(nav('同步'));
  assert.ok(document.querySelector('.mobile-settings').textContent.includes('加入 iPhone 主畫面'));
  assert.ok(document.querySelector('.cloud-panel').open);
  await click(nav('複習'));
  while (document.querySelector('.flashcard')) {
    await click(document.querySelector('.flip-button'));
    await click(document.querySelector('.rating-good'));
  }
  assert.equal(document.querySelector('.review-picker').hidden, false, 'Finishing practice brings the count form back');
  assert.ok(document.querySelector('.mobile-header'));
  const sideEntries = await lookupStudyWord('側');
  const side = sideEntries.find(entry => entry.reading === 'がわ');
  const withSide = collectManualWord(parseLibrary(window.localStorage.getItem(STORAGE_KEY)), { word: '側', reading: 'がわ', definitions: [side] }, now);
  const sideJSON = libraryJSON(withSide);
  window.localStorage.setItem(STORAGE_KEY, sideJSON);
  await act(async () => window.dispatchEvent(new window.StorageEvent('storage', { key: STORAGE_KEY, newValue: sideJSON })));
  await click(nav('收藏'));
  await click(document.querySelector('[aria-label="查看單字 側"]'));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 100)); });
  assert.ok(document.querySelector('[aria-label="學習 側（そば）"]'), 'Saved cards load alternative readings from the full dictionary');
  await click(document.querySelector('[aria-label="學習 側（そば）"]'));
  const chosenSide = parseLibrary(window.localStorage.getItem(STORAGE_KEY)).find(card => card.word === '側');
  assert.equal(chosenSide.reading, 'そば');
  assert.equal(chosenSide.definitions[0].reading, 'そば');
  await click(document.querySelector('[aria-label="朗讀單字"]'));
  assert.equal(spoken.at(-1), 'そば');
  await click(document.querySelector('.word-close'));
  await click(document.querySelector('[aria-label="查看單字 側"]'));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 100)); });
  assert.equal(document.querySelector('[aria-label="學習 側（そば）"]').checked, true, 'Reopening retains the chosen reading');
  await click(document.querySelector('.word-close'));
  await click(nav('複習'));
  await act(async () => document.querySelector('.review-picker').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
  assert.equal(document.querySelector('.flashcard h2').textContent, '側');
  await click(document.querySelector('.flip-button'));
  assert.ok(document.querySelector('.review-reading').textContent.includes('そば'));
  assert.ok(document.querySelector('.flashcard-answer').textContent.includes('(place) near by'));
  assert.equal(document.querySelector('button button'), null);
  console.log('Mobile UI passed: review/library/settings tabs, hidden answers, bilingual examples, speech, persisted ratings and no video playback.');
} finally {
  await act(async () => root.unmount()); await server.close(); await window.happyDOM.cancelAsync(); globalThis.fetch = originalFetch;
}
